"""Initial data cleaning + EDA for the freight rate prediction take-home.

Run with:
    python notebooks_or_scripts/eda.py

Reads data/train_test.csv, data/validation.csv, and data/december_chart_inputs.csv,
confirms the pre-shared facts about the dataset programmatically, and writes
figures to reports/figures/ plus a written summary to reports/eda_findings.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.data import clean_loads, load_december, load_train_test, load_validation
from src.features import build_features
from src.validation import assert_no_leakage, time_based_folds

FIG_DIR = ROOT / "reports" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)
REPORT_PATH = ROOT / "reports" / "eda_findings.md"

DECEMBER_EXPECTED_COLUMNS = [
    "pickup",
    "delivery",
    "distance",
    "equipment",
    "weight",
    "date",
    "predicted_rate",
]


def section(title: str) -> None:
    print(f"\n{'=' * 80}\n{title}\n{'=' * 80}")


def md_table(df: pd.DataFrame, index_name: str = "") -> str:
    """Render a DataFrame as a GitHub-flavored markdown table without extra deps."""
    df = df.reset_index()
    if index_name:
        df = df.rename(columns={df.columns[0]: index_name})
    headers = [str(c) for c in df.columns]
    rows = [[str(v) for v in row] for row in df.to_numpy()]
    widths = [max(len(h), *(len(r[i]) for r in rows)) if rows else len(h) for i, h in enumerate(headers)]
    header_line = "| " + " | ".join(h.ljust(w) for h, w in zip(headers, widths)) + " |"
    sep_line = "| " + " | ".join("-" * w for w in widths) + " |"
    row_lines = ["| " + " | ".join(v.ljust(w) for v, w in zip(r, widths)) + " |" for r in rows]
    return "\n".join([header_line, sep_line, *row_lines])


def main() -> None:
    lines: list[str] = []
    lines.append("# EDA Findings: Freight Rate Prediction\n")
    lines.append(
        "Generated by `notebooks_or_scripts/eda.py` from `data/train_test.csv`, "
        "`data/validation.csv`, and `data/december_chart_inputs.csv`.\n"
    )

    # ------------------------------------------------------------------
    # Load raw data
    # ------------------------------------------------------------------
    section("Loading data")
    train = load_train_test()
    val = load_validation()
    dec = load_december()

    n_train, n_val, n_dec = len(train), len(val), len(dec)
    train_date_min, train_date_max = train["date"].min(), train["date"].max()
    val_date_min, val_date_max = val["date"].min(), val["date"].max()

    print(f"train_test.csv: {n_train:,} rows, {train_date_min.date()} to {train_date_max.date()}")
    print(f"validation.csv: {n_val:,} rows, {val_date_min.date()} to {val_date_max.date()}")
    print(f"december_chart_inputs.csv: {n_dec} rows")

    assert n_train == 48_000, f"expected 48,000 train rows, got {n_train}"
    assert n_val == 12_000, f"expected 12,000 validation rows, got {n_val}"
    assert n_dec == 31, f"expected 31 december rows, got {n_dec}"

    lines.append("## 1. Row counts and date ranges\n")
    lines.append(
        f"- `train_test.csv`: **{n_train:,} rows**, "
        f"{train_date_min.date()} to {train_date_max.date()} (confirmed).\n"
        f"- `validation.csv`: **{n_val:,} rows**, "
        f"{val_date_min.date()} to {val_date_max.date()} (confirmed). "
        "This is a genuine out-of-time set relative to train — no date overlap.\n"
        f"- `december_chart_inputs.csv`: **{n_dec} rows**, one per December 2025 date.\n"
    )

    # ------------------------------------------------------------------
    # Column set checks
    # ------------------------------------------------------------------
    section("Column checks")
    train_cols = list(train.columns)
    val_cols = list(val.columns)
    dec_cols = list(dec.columns)
    print("train_test columns:", train_cols)
    print("validation columns:", val_cols)
    print("december columns:", dec_cols)

    assert set(train_cols) - set(val_cols) == {"posted_rate"}
    assert dec_cols == DECEMBER_EXPECTED_COLUMNS
    assert not {"pickup_lat", "pickup_lon", "delivery_lat", "delivery_lon", "market_index", "quote_signal"} & set(dec_cols)

    lines.append("## 2. Column set confirmation\n")
    lines.append(
        f"- `train_test.csv` columns: `{train_cols}`\n"
        f"- `validation.csv` columns: `{val_cols}` (same as train minus `posted_rate`, confirmed).\n"
        f"- `december_chart_inputs.csv` columns: `{dec_cols}` — confirmed **only 7 columns**, "
        "no lat/lon, no `market_index`, no `quote_signal`.\n"
    )

    # december fixed-lane check
    dec_lane_ok = (
        (dec["pickup"] == "Lexington").all()
        and (dec["delivery"] == "Fort Wayne").all()
        and np.isclose(dec["distance"], 360).all()
        and (dec["equipment"] == "Dry Van").all()
        and np.isclose(dec["weight"], 32000).all()
        and dec["date"].nunique() == 31
    )
    assert dec_lane_ok
    lines.append(
        "- December fixed-lane confirmed: Lexington -> Fort Wayne, 360 mi, Dry Van, "
        "32,000 lb, one row per December 2025 date. `december_chart_inputs.csv` is "
        "otherwise left untouched (no cleaning applied), per instructions.\n"
    )

    # ------------------------------------------------------------------
    # Missingness
    # ------------------------------------------------------------------
    section("Missingness")
    miss_train = train.isna().mean().sort_values(ascending=False) * 100
    miss_val = val.isna().mean().sort_values(ascending=False) * 100
    miss_table = pd.DataFrame({"train_test_%": miss_train, "validation_%": miss_val}).round(2)
    miss_table = miss_table[(miss_table["train_test_%"] > 0) | (miss_table["validation_%"] > 0)]
    print(miss_table)

    weight_miss_train = train["weight"].isna().mean() * 100
    weight_miss_val = val["weight"].isna().mean() * 100
    mi_miss_train = train["market_index"].isna().mean() * 100
    mi_miss_val = val["market_index"].isna().mean() * 100

    lines.append("## 3. Missingness\n")
    lines.append(md_table(miss_table, "column") + "\n")
    lines.append(
        f"\n- `weight` missing: {weight_miss_train:.2f}% train, {weight_miss_val:.2f}% validation "
        "(confirmed ~0.6%).\n"
        f"- `market_index` missing: {mi_miss_train:.2f}% train, {mi_miss_val:.2f}% validation "
        "(confirmed ~0.8-2%).\n"
        "- Handled in `clean_loads()` via median imputation plus `*_was_missing` flag columns.\n"
    )

    # ------------------------------------------------------------------
    # Weight sign-flip check
    # ------------------------------------------------------------------
    section("Weight sign-flip check")
    neg_train = train.loc[train["weight"] < 0, "weight"]
    pos_train = train.loc[train["weight"] > 0, "weight"]
    neg_val = val.loc[val["weight"] < 0, "weight"]
    pos_val = val.loc[val["weight"] > 0, "weight"]

    n_neg_train, n_neg_val = len(neg_train), len(neg_val)
    print(f"Negative weight rows: train={n_neg_train}, validation={n_neg_val}")

    assert n_neg_train == 292, f"expected 292 negative weights in train, got {n_neg_train}"
    assert n_neg_val == 145, f"expected 145 negative weights in validation, got {n_neg_val}"

    desc_compare = pd.DataFrame(
        {
            "positive_weight (train)": pos_train.describe(),
            "abs(negative_weight) (train)": neg_train.abs().describe(),
        }
    ).round(1)
    print(desc_compare)

    lines.append("## 4. Weight sign-flip artifact (confirmed)\n")
    lines.append(
        f"- Negative `weight` rows: **{n_neg_train} in train** (confirmed 292), "
        f"**{n_neg_val} in validation** (confirmed 145).\n\n"
        + md_table(desc_compare, "stat")
        + "\n\n"
        "- `abs(negative_weight)` closely tracks the positive-weight distribution "
        "(same ~5,000-47,500 range, comparable mean/std) — this is a sign-flip "
        "artifact, not a distinct erroneous population. Fixed via `.abs()` in "
        "`clean_loads()` rather than dropping the rows.\n"
    )

    # ------------------------------------------------------------------
    # Clean data for downstream analysis
    # ------------------------------------------------------------------
    train_clean = clean_loads(train)
    val_clean = clean_loads(val)

    # ------------------------------------------------------------------
    # Correlation table
    # ------------------------------------------------------------------
    section("Correlation vs posted_rate")
    corr_cols = ["distance", "weight", "market_index", "quote_signal"]
    corr = train_clean[corr_cols + ["posted_rate"]].corr()["posted_rate"].drop("posted_rate")
    corr = corr.sort_values(ascending=False)
    print(corr)

    dist_corr = corr["distance"]
    assert dist_corr > 0.85, f"expected distance corr ~0.91, got {dist_corr}"

    lines.append("## 5. Correlation with `posted_rate` (train, cleaned)\n")
    lines.append(md_table(corr.to_frame("corr_with_posted_rate").round(4), "feature") + "\n")
    lines.append(
        f"\n- `distance` correlates **{dist_corr:.3f}** with `posted_rate` (confirmed ~0.91) "
        "— by far the dominant single predictor.\n"
    )

    fig, ax = plt.subplots(figsize=(6, 4))
    corr.plot(kind="barh", ax=ax, color="#2f6f76")
    ax.set_xlabel("Correlation with posted_rate")
    ax.set_title("Feature correlation with posted_rate (train)")
    ax.axvline(0, color="black", linewidth=0.8)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "correlation_with_posted_rate.png", dpi=150)
    plt.close(fig)

    # ------------------------------------------------------------------
    # $/mile by equipment
    # ------------------------------------------------------------------
    section("$/mile by equipment")
    train_clean["rate_per_mile"] = train_clean["posted_rate"] / train_clean["distance"]
    rpm_by_equip = train_clean.groupby("equipment")["rate_per_mile"].agg(["mean", "median", "std", "count"])
    rpm_by_equip = rpm_by_equip.sort_values("mean")
    print(rpm_by_equip)

    equip_order = list(rpm_by_equip.index)
    assert equip_order == ["Dry Van", "Flatbed", "Reefer"], f"unexpected equipment $/mi ordering: {equip_order}"

    lines.append("## 6. $/mile by equipment (train)\n")
    lines.append(md_table(rpm_by_equip.round(3), "equipment") + "\n")
    lines.append(
        f"\n- Confirmed ordering **Dry Van < Flatbed < Reefer** in $/mile "
        f"({rpm_by_equip['mean']['Dry Van']:.3f} < {rpm_by_equip['mean']['Flatbed']:.3f} < "
        f"{rpm_by_equip['mean']['Reefer']:.3f}).\n"
    )

    fig, ax = plt.subplots(figsize=(6, 4))
    rpm_by_equip["mean"].plot(kind="bar", ax=ax, color="#2f6f76", yerr=rpm_by_equip["std"], capsize=4)
    ax.set_ylabel("$/mile")
    ax.set_title("Mean $/mile by equipment type (train)")
    ax.set_xlabel("")
    plt.xticks(rotation=0)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "rate_per_mile_by_equipment.png", dpi=150)
    plt.close(fig)

    # ------------------------------------------------------------------
    # Distance-detrended residual vs market_index / quote_signal
    # ------------------------------------------------------------------
    section("Distance-detrended residual correlation")
    slope, intercept = np.polyfit(train_clean["distance"], train_clean["posted_rate"], 1)
    train_clean["residual"] = train_clean["posted_rate"] - (slope * train_clean["distance"] + intercept)
    resid_corr = train_clean[["market_index", "quote_signal", "residual"]].corr()["residual"].drop("residual")
    print(resid_corr)

    assert resid_corr.abs().max() < 0.1, f"expected weak residual correlation <0.1, got {resid_corr}"

    lines.append("## 7. market_index / quote_signal vs distance-detrended residual\n")
    lines.append(
        f"- After removing the linear distance trend (`posted_rate ~ {slope:.3f} * distance + {intercept:.1f}`), "
        f"residual correlation with `market_index` is **{resid_corr['market_index']:.4f}** and with "
        f"`quote_signal` is **{resid_corr['quote_signal']:.4f}** — both confirmed **< 0.1**, i.e. weak. "
        "Neither variable explains meaningful residual variance beyond distance alone.\n"
    )

    # ------------------------------------------------------------------
    # market_index seasonality
    # ------------------------------------------------------------------
    section("market_index seasonality")
    train_clean["month"] = train_clean["date"].dt.to_period("M")
    val_clean["month"] = val_clean["date"].dt.to_period("M")

    mi_by_month_train = train_clean.groupby("month")["market_index"].mean()
    mi_by_month_val = val_clean.groupby("month")["market_index"].mean()
    train_yearly_mean = train_clean["market_index"].mean()
    val_nov_dec_mean = val_clean["market_index"].mean()

    print(mi_by_month_train)
    print(mi_by_month_val)
    print(f"train yearly mean: {train_yearly_mean:.4f}, validation Nov-Dec mean: {val_nov_dec_mean:.4f}")

    jan_val = mi_by_month_train.iloc[0]
    sep_val = mi_by_month_train[mi_by_month_train.index.astype(str).str.endswith("09")].iloc[0]
    may_val = mi_by_month_train[mi_by_month_train.index.astype(str).str.endswith("05")].iloc[0]
    peak_month = mi_by_month_train.idxmax()
    assert val_nov_dec_mean < train_yearly_mean, "expected validation Nov-Dec market_index mean below train yearly mean"

    lines.append("## 8. `market_index` seasonality (confirmed)\n")
    lines.append("**By month (train):**\n\n" + md_table(mi_by_month_train.round(4).to_frame("mean_market_index"), "month") + "\n")
    lines.append("\n**By month (validation):**\n\n" + md_table(mi_by_month_val.round(4).to_frame("mean_market_index"), "month") + "\n")
    lines.append(
        f"\n- Train shows a seasonal arc: low around Jan ({jan_val:.3f}) and Sep ({sep_val:.3f}), "
        f"peaking around {peak_month} ({mi_by_month_train.max():.3f}, at/near May).\n"
        f"- Train yearly mean: **{train_yearly_mean:.4f}**. Validation Nov-Dec mean: "
        f"**{val_nov_dec_mean:.4f}** — confirmed **lower** than the train yearly mean, "
        "consistent with the downswing after the mid-year peak. This is a real seasonal "
        "shift the model needs to generalize across, not just interpolate within train.\n"
    )

    fig, ax = plt.subplots(figsize=(9, 4.5))
    mi_by_month_train.index = mi_by_month_train.index.astype(str)
    mi_by_month_val.index = mi_by_month_val.index.astype(str)
    ax.plot(mi_by_month_train.index, mi_by_month_train.values, marker="o", label="train (Jan-Oct 2025)", color="#2f6f76")
    ax.plot(mi_by_month_val.index, mi_by_month_val.values, marker="o", label="validation (Nov-Dec 2025)", color="#c0562e")
    ax.axhline(train_yearly_mean, color="#2f6f76", linestyle="--", linewidth=0.8, label="train yearly mean")
    ax.set_ylabel("mean market_index")
    ax.set_title("market_index by month: train seasonal arc vs validation shift")
    ax.legend()
    plt.xticks(rotation=45)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "market_index_seasonality.png", dpi=150)
    plt.close(fig)

    # ------------------------------------------------------------------
    # Validation-only cities
    # ------------------------------------------------------------------
    section("Validation-only cities")
    train_cities = set(train["pickup"]) | set(train["delivery"])
    val_cities = set(val["pickup"]) | set(val["delivery"])
    val_only_cities = sorted(val_cities - train_cities)
    print(f"Validation-only cities ({len(val_only_cities)}): {val_only_cities}")

    expected_val_only = {
        "Allentown", "Charlotte", "Chicago", "Jackson",
        "Knoxville", "Laredo", "Norfolk", "San Diego",
    }
    assert set(val_only_cities) == expected_val_only, (
        f"expected val-only cities {expected_val_only}, got {set(val_only_cities)}"
    )

    lines.append("## 9. Validation-only cities (confirmed, encoding caution)\n")
    lines.append(
        f"- **{len(val_only_cities)} cities** appear as pickup/delivery in `validation.csv` "
        f"that never appear in `train_test.csv`: **{', '.join(val_only_cities)}**.\n"
        "- This rules out naive city one-hot encoding: a model fit only on train-seen "
        "city dummies will have no learned coefficient for these 8 cities at inference "
        "time. Any city-based feature needs a fallback (e.g. lat/lon-based features, "
        "regional grouping, or a hashing/embedding approach that degrades gracefully "
        "for unseen categories) rather than a fixed one-hot vocabulary.\n"
    )

    # ------------------------------------------------------------------
    # Write markdown report
    # ------------------------------------------------------------------
    section("Writing report")
    lines.append("## 10. Summary of key takeaways\n")
    lines.append(
        "- Dataset sizes and date ranges confirmed: 48,000 train rows (2025-01-01 to "
        "2025-10-31), 12,000 validation rows (2025-11-01 to 2025-12-31, genuinely "
        "out-of-time), 31 December chart rows (fixed Lexington->Fort Wayne lane).\n"
        "- `weight` has a sign-flip data quality issue (292 negative in train, 145 in "
        "validation) that is fixed with `.abs()`, not row-dropping — confirmed the "
        "negative-magnitude distribution matches the positive one.\n"
        "- `weight` and `market_index` have low missingness (~0.6% and ~0.8-2%); both "
        "median-imputed with `*_was_missing` flags retained.\n"
        "- `distance` is the dominant predictor (corr ~0.91 with `posted_rate`); "
        "`equipment` adds a clean $/mile ordering (Dry Van < Flatbed < Reefer).\n"
        "- `market_index` and `quote_signal` add little beyond distance+equipment "
        "(<0.1 correlation with the distance-detrended residual) — they may still "
        "help at the margins but are not primary drivers.\n"
        "- `market_index` has a real seasonal arc across train (low Jan/Sep, peak near "
        "May) and validation's Nov-Dec average sits below the train yearly mean — "
        "any model or feature relying on `market_index` needs to account for this "
        "shift rather than assume train-period stationarity.\n"
        "- 8 cities appear only in validation, never in train — naive one-hot city "
        "encoding will not generalize to them; plan features accordingly.\n"
    )

    REPORT_PATH.write_text("\n".join(lines))
    print(f"\nWrote {REPORT_PATH}")
    print(f"Wrote figures to {FIG_DIR}")

    # ------------------------------------------------------------------
    # Feature engineering + time-based CV fold sanity check (console only,
    # not written to reports/eda_findings.md)
    # ------------------------------------------------------------------
    section("Feature engineering + validation fold sanity check")
    # rebuild from a fresh clean copy: train_clean has since accumulated ad-hoc
    # analysis columns (rate_per_mile, residual, month) from the sections above
    train_for_features = clean_loads(train)
    train_features = build_features(train_for_features)
    print(f"build_features added columns: {sorted(set(train_features.columns) - set(train_for_features.columns))}")

    folds = time_based_folds(train_features, n_folds=3)
    dates = train_features["date"]
    for fold in folds:
        assert_no_leakage(fold["train_idx"], fold["val_idx"], dates)
        train_dates = dates.loc[fold["train_idx"]]
        val_dates = dates.loc[fold["val_idx"]]
        print(
            f"Fold {fold['fold']}: "
            f"train [{train_dates.min().date()} .. {train_dates.max().date()}] "
            f"({len(fold['train_idx']):,} rows) | "
            f"val [{val_dates.min().date()} .. {val_dates.max().date()}] "
            f"({len(fold['val_idx']):,} rows) — no leakage confirmed"
        )


if __name__ == "__main__":
    main()
